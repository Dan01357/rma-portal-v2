-- ==============================================================================
-- CREATE TABLE: public.supplier_claims (Return to Vendor Debit Claims)
-- Execute in Supabase SQL Editor if you want a dedicated table for RTV claims.
-- Note: The application also automatically persists and syncs RTV claims in
-- rma_settings and updates the linked rma_reports audit trail.
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.supplier_claims (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_number text UNIQUE NOT NULL,      -- e.g. RTV-2026-0001-HY67
  supplier_name text NOT NULL,
  generated_by text NOT NULL,
  total_quantity integer DEFAULT 1,
  total_claim_amount numeric(12, 2) DEFAULT 0.00,
  items jsonb DEFAULT '[]'::jsonb,        -- Array of bundled items and RMA numbers
  status text DEFAULT 'generated',        -- 'generated', 'acknowledged', 'settled', 'cancelled'
  notes text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_supplier_claims_claim_number ON public.supplier_claims(claim_number);
CREATE INDEX IF NOT EXISTS idx_supplier_claims_supplier_name ON public.supplier_claims(supplier_name);
CREATE INDEX IF NOT EXISTS idx_supplier_claims_created_at ON public.supplier_claims(created_at DESC);

-- Enable RLS and grant privileges
ALTER TABLE public.supplier_claims ENABLE ROW LEVEL SECURITY;
GRANT ALL PRIVILEGES ON TABLE public.supplier_claims TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Allow anon full access supplier_claims" ON public.supplier_claims;
CREATE POLICY "Allow anon full access supplier_claims" ON public.supplier_claims
  FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);
