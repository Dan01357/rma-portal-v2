-- 1. CLEAN UP OLD UNUSED TABLES (Safe to re-run)
DROP TABLE IF EXISTS public.rma_tickets CASCADE;
DROP TABLE IF EXISTS public.rma_items CASCADE;
DROP TABLE IF EXISTS public.products CASCADE;
DROP TABLE IF EXISTS public.rma_reports CASCADE;

-- 2. CREATE PRODUCTS CATALOG TABLE
CREATE TABLE public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  barcode text UNIQUE NOT NULL,       -- Scanned Barcode (e.g., 2310943156)
  code text,                          -- SKU / Item Code (e.g., P2678P)
  name text NOT NULL,                 -- Product Name
  price numeric(12,2) DEFAULT 0.00,
  price_with_vat numeric(12,2) DEFAULT 0.00,
  supplier_name text DEFAULT 'Savemore',
  brand_name text,
  unit_name text DEFAULT 'pc',
  has_serial_numbers boolean DEFAULT false,
  image_url text,                     -- Optional Reference Photo uploaded by Admin
  is_verified boolean DEFAULT true,   -- false = auto-logged from unknown scan, true = verified by admin
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX idx_products_barcode ON public.products(barcode);
CREATE INDEX idx_products_code ON public.products(code);
CREATE INDEX idx_products_is_verified ON public.products(is_verified);

-- 3. CREATE RMA REPORTS TABLE (With Proof Photos, Reason, GPS & Reporter Contact)
CREATE TABLE public.rma_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  rma_number text NOT NULL,
  barcode text NOT NULL,
  code text,
  name text NOT NULL,
  quantity integer DEFAULT 1,
  supplier_name text,
  price numeric(12,2) DEFAULT 0.00,
  price_with_vat numeric(12,2) DEFAULT 0.00,
  unit_name text DEFAULT 'pc',
  status text DEFAULT 'pending',      -- 'pending', 'pending_admin_details', 'resolved'
  location text,                      -- Warehouse rack / slot (optional)
  reason text DEFAULT 'Damaged Box / Crushed Packaging',
  explanation text,
  photos jsonb DEFAULT '[]'::jsonb,   -- Array of proof image URLs
  gps_latitude numeric(10,7),         -- Auto GPS Latitude (only if hardware accurate <= 150m)
  gps_longitude numeric(10,7),        -- Auto GPS Longitude
  gps_accuracy numeric(8,2),          -- Accuracy in meters
  gps_timestamp timestamptz,
  reporter_name text,                 -- Name of person reporting
  reporter_contact text,              -- Phone number or Email
  reported_by text DEFAULT 'Customer / Reporter',
  notes text,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX idx_rma_reports_barcode ON public.rma_reports(barcode);
CREATE INDEX idx_rma_reports_status ON public.rma_reports(status);

-- ==============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES FOR PUBLIC ACCESS
-- ==============================================================================

ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rma_reports ENABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.products TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.rma_reports TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- Policies for public.products
DROP POLICY IF EXISTS "Allow anon read all products" ON public.products;
CREATE POLICY "Allow anon read all products" ON public.products
  FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow anon insert products" ON public.products;
CREATE POLICY "Allow anon insert products" ON public.products
  FOR INSERT TO anon, authenticated, service_role WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update products" ON public.products;
CREATE POLICY "Allow anon update products" ON public.products
  FOR UPDATE TO anon, authenticated, service_role USING (true) WITH CHECK (true);

-- Policies for public.rma_reports
DROP POLICY IF EXISTS "Allow anon read all rma_reports" ON public.rma_reports;
CREATE POLICY "Allow anon read all rma_reports" ON public.rma_reports
  FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow anon insert rma_reports" ON public.rma_reports;
CREATE POLICY "Allow anon insert rma_reports" ON public.rma_reports
  FOR INSERT TO anon, authenticated, service_role WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update rma_reports" ON public.rma_reports;
CREATE POLICY "Allow anon update rma_reports" ON public.rma_reports
  FOR UPDATE TO anon, authenticated, service_role USING (true) WITH CHECK (true);

