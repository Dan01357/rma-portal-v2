-- 1. CREATE ADMIN USERS & EMPLOYEE ROLES TABLE
CREATE TABLE IF NOT EXISTS public.admin_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text UNIQUE NOT NULL,
  role text DEFAULT 'inventory_staff', -- 'super_admin', 'admin', 'inventory_staff', 'viewer'
  is_active boolean DEFAULT true,      -- true = active employee, false = resigned
  department text DEFAULT 'General',
  last_login timestamptz,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_admin_users_email ON public.admin_users(email);
CREATE INDEX IF NOT EXISTS idx_admin_users_active ON public.admin_users(is_active);

-- Enable RLS & grant permissions
ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.admin_users TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Allow anon read all admin_users" ON public.admin_users;
CREATE POLICY "Allow anon read all admin_users" ON public.admin_users
  FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow anon insert admin_users" ON public.admin_users;
CREATE POLICY "Allow anon insert admin_users" ON public.admin_users
  FOR INSERT TO anon, authenticated, service_role WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update admin_users" ON public.admin_users;
CREATE POLICY "Allow anon update admin_users" ON public.admin_users
  FOR UPDATE TO anon, authenticated, service_role USING (true) WITH CHECK (true);

-- 2. CREATE OTP VERIFICATION TOKENS TABLE
CREATE TABLE IF NOT EXISTS public.otp_tokens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  otp_code text NOT NULL,
  expires_at timestamptz NOT NULL,
  is_used boolean DEFAULT false,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE public.otp_tokens ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.otp_tokens TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Allow anon manage otp_tokens" ON public.otp_tokens;
CREATE POLICY "Allow anon manage otp_tokens" ON public.otp_tokens
  FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);

