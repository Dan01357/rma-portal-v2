-- ==============================================================================
-- CREATE TABLE: public.credit_memos
-- Dedicated Table for Finance Credit Memos in Supabase
-- Run this script in your Supabase SQL Editor:
-- Dashboard > SQL Editor > New query > Paste & Run
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.credit_memos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  credit_memo_number text UNIQUE NOT NULL,
  rma_number text NOT NULL,
  report_id bigint,
  barcode text NOT NULL,
  product_name text NOT NULL,
  sku text,
  supplier_name text,
  company text DEFAULT 'Wholesale Distribution',
  customer_ae_name text,
  customer_ae_email text,
  quantity numeric DEFAULT 1,
  unit_name text DEFAULT 'pc',
  unit_price numeric(12, 2) DEFAULT 0.00,
  amount numeric(12, 2) DEFAULT 0.00,
  pull_out_ref text NOT NULL,
  pull_out_date date DEFAULT CURRENT_DATE,
  credit_amount numeric(12, 2) NOT NULL,
  credit_issued_by text NOT NULL,
  credit_issued_by_email text,
  credit_issued_at timestamptz DEFAULT now(),
  notes text,
  status text DEFAULT 'issued',
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

-- Fast Lookups and Indexes
CREATE INDEX IF NOT EXISTS idx_credit_memos_cm_number ON public.credit_memos(credit_memo_number);
CREATE INDEX IF NOT EXISTS idx_credit_memos_rma_number ON public.credit_memos(rma_number);
CREATE INDEX IF NOT EXISTS idx_credit_memos_barcode ON public.credit_memos(barcode);
CREATE INDEX IF NOT EXISTS idx_credit_memos_pull_out_ref ON public.credit_memos(pull_out_ref);
CREATE INDEX IF NOT EXISTS idx_credit_memos_issued_at ON public.credit_memos(credit_issued_at DESC);

-- Enable Row Level Security (RLS) & Grant Full Permissions to Web App
ALTER TABLE public.credit_memos ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.credit_memos TO anon, authenticated, service_role;

DROP POLICY IF EXISTS "Allow anon read all credit_memos" ON public.credit_memos;
CREATE POLICY "Allow anon read all credit_memos" ON public.credit_memos
  FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow anon insert credit_memos" ON public.credit_memos;
CREATE POLICY "Allow anon insert credit_memos" ON public.credit_memos
  FOR INSERT TO anon, authenticated, service_role WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update credit_memos" ON public.credit_memos;
CREATE POLICY "Allow anon update credit_memos" ON public.credit_memos
  FOR UPDATE TO anon, authenticated, service_role USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon delete credit_memos" ON public.credit_memos;
CREATE POLICY "Allow anon delete credit_memos" ON public.credit_memos
  FOR DELETE TO anon, authenticated, service_role USING (true);
